#!/usr/bin/env python3
"""Generate the colour-only Herdr override from the Omarchy palette."""
import pathlib, tomllib
ROOT = pathlib.Path(__file__).resolve().parents[1]
c = tomllib.loads((ROOT / 'theme/colors.toml').read_text())
mapping = dict(sidebar_bg='dark_background', active_row_bg='selection', selection_bg='selection',
               surface0='lighter_background', surface1='selection', surface_dim='background',
               overlay0='muted', overlay1='light_foreground', text='foreground', subtext0='muted',
               accent='accent', mauve='magenta', green='green', yellow='yellow', red='red',
               blue='blue', teal='cyan', peach='orange')
text = '# Generated by scripts/build_herdr.py; colours only.\n[theme]\nname = "terminal"\nauto_switch = false\n\n[theme.custom]\npanel_bg = "reset"\n'
text += ''.join(f'{key} = "{c[value]}"\n' for key, value in mapping.items())
text += f'\n[ui]\naccent = "{c["accent"]}"\n'
(ROOT / 'theme/herdr.toml').write_text(text)
