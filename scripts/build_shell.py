#!/usr/bin/env python3
"""Build only the shell sections this theme customises; never modify global templates."""
import pathlib, tomllib
ROOT = pathlib.Path(__file__).resolve().parents[1]
c = tomllib.loads((ROOT / 'theme/colors.toml').read_text())
def write(section, values):
    def value(v):
        if isinstance(v, bool): return str(v).lower()
        if isinstance(v, str): return '"' + v + '"'
        return str(v)
    text = '# Generated by scripts/build_shell.py; edit the source, then rebuild.\n'
    text += f'[{section}]\n' + ''.join(f'{k} = {value(v)}\n' for k,v in values.items())
    (ROOT / f'theme/shell.{section}.toml').write_text(text)
base = {'background': c['lighter_background'], 'background-alpha':1.0, 'text':c['foreground'],
        'border':c['accent'], 'border-alpha':1.0}
write('bar', {'background':c['background'],'background-alpha':1.0,'text':c['foreground'],
              'active':c['accent'],'scale-with-font':True,'size-horizontal':26,'size-vertical':28})
for section in ('popups','tooltip','notifications'):
    values = dict(base)
    if section == 'notifications': values['countdown'] = c['accent']
    write(section, values)
for section in ('launcher','menu'):
    write(section, {**base,'scrim':c['background'],'scrim-alpha':0.6,
        'selected-background':c['selection'],'selected-background-alpha':1.0,
        'selected-text':c['selection_foreground'],'selected-border':c['accent'],'selected-border-alpha':1.0})
controls = {}
for state,fill,border in [('normal',0.04,c['muted']),('hover-cursor',0.08,c['accent']),('focus',0.08,c['accent']),('selected',0.15,c['accent'])]:
    controls.update({f'{state}-color':c['foreground'],f'{state}-fill-alpha':fill,
        f'{state}-border':border,f'{state}-border-width':1,f'{state}-border-alpha':1.0})
controls.update({'pressed-fill-alpha':0.22,'selection-fill-alpha':0.35})
write('controls',controls)
write('lock',{**base,'background':c['background'],'placeholder':c['muted'],
    'text-error':c['red'],'border-active':c['accent'],'border-error':c['red'],
    'selection':c['selection'],'selection-alpha':1.0})
write('polkit',{**base,'scrim':c['background'],'scrim-alpha':0.6,
    'text-error':c['red'],'border-error':c['red'],'accent':c['accent']})
print('Built 9 targeted shell sections')
